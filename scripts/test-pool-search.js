const assert=require('node:assert/strict'),G=require('../web/placement-engine'),T=require('@turf/turf'),P=require('proj4');
const origin=[-111.8,41.2],dimensions={width:4,length:8,deck:1.2};
const input={boundary:G.rectangle(origin,0,0,70,70),toleranceM:.3,obstacles:[],coverage:{},survey:null};
const options={origin,dimensions,setbackM:3,ruleSource:'Scenario only',maxTests:100};
const r=G.search(input,options);
assert(r.tested<=100&&r.candidates.length>0);assert.equal(r.exhaustive,false);
assert(r.candidates.every(c=>c.result.status==='preliminary'&&!c.result.precisePlacement));
const obstacle={name:'Utility easement',geometry:G.rectangle(origin,0,0,15,70),clearanceM:0,source:'https://example.org/record',reviewed:true};
const restricted=G.search({...input,obstacles:[obstacle]},options);
assert(restricted.candidates.length>0);
assert(restricted.candidates.every(c=>c.result.checks.filter(x=>x.check==='Utility easement').every(x=>x.passed)));
const blocked=G.search({...input,boundary:G.rectangle(origin,0,0,5,5)},options);
assert.equal(blocked.status,'no_sampled_candidate');assert.match(blocked.limitation,/does not establish/);
const rotation=G.assembly(origin,{...dimensions,rotation:90});
const centre=T.center(rotation[2].geometry).geometry.coordinates,xy=P('EPSG:4326',G.projection(origin),centre);
assert(Math.abs(xy[0])<.01&&Math.abs(xy[1]-(4/2+1.2+1.5))<.01,'Equipment moves with rotated assembly');
const hole=structuredClone(input.boundary);hole.geometry.coordinates.push(G.rectangle(origin,0,0,20,20).geometry.coordinates[0].reverse());
const withHole=G.search({...input,boundary:hole},options);assert(withHole.candidates.length>0);
for(const c of withHole.candidates)assert.equal(c.result.conflicts.length,0);
assert.throws(()=>G.search(input,{...options,maxTests:10000}),/limits/);
assert.throws(()=>G.search(input,{...options,dimensions:{...dimensions,deck:-1}}),/deck/);
console.log('Pool search: rotated assembly, utility exclusion, holes, narrow lot, bounded sampling and unresolved coverage passed.');
