'use strict';
const assert = require('node:assert/strict');
const W = require('../web/permit-workflow');
const report = { parcel: { county: 'Example', id: 'test-parcel', attrs: { PARCEL_ADD: 'Example project' } }, date: '2026-11-07', facts: { jurisdiction: 'Example City', packet: { items: [{ title: 'Structural plans', status: 'ready' }], rows: [['Area','2,400 sq ft','User plans']] } } };
let p = W.create(report);
const run = command => p = W.apply(p,command);
const fails = (command, pattern) => assert.throws(()=>W.apply(p,command),pattern);
const file = (id,family) => ({type:'document',document:{id,family:family||id,name:'plans-'+id+'.pdf',hash:'a'.repeat(64),role:'plan'}});
assert.equal(p.requirements[1].state,'missing','An engine ready status must not approve a filing requirement');
fails({type:'prepare',reviewer:'Builder',reviewed:true},/blockers/);
run({type:'application',applicant:'Applicant',owner:'Owner',description:'Single-family residence'});
run(file('v1'));
assert(W.blockers(p,'initial').length,'Uploading plans must not approve requirements');
for(const r of p.requirements) run({type:'requirement',id:r.id,state:'reviewed',reviewer:'Reviewer',note:'Checked current scope and required sheets',documentIds:['v1']});
assert(W.blockers(p,'initial').includes('Rules for this property have not been checked.'));
function reviewAreas(){
 run({type:'area_map',snapshot:{parcelKey:p.propertyKey,at:'2026-11-12',layers:[{id:'municipal',state:'checked',features:[{name:'Example City'}]}]}});
 for(const r of require('../web/area-rules').rules(p).filter(r=>r.stage==='submission'))run({type:'rule_review',id:r.id,state:'not-applicable',reviewer:'Test reviewer',note:'Synthetic authority correspondence confirms no additional prerequisite',url:'https://example.org/authority-letter'});
}
reviewAreas();assert.deepEqual(W.blockers(p,'initial'),[]);
run({type:'prepare',reviewer:'Reviewer',reviewed:true});
const first = W.currentPackage(p,'initial');
run({type:'prepare',reviewer:'Reviewer',reviewed:true});
assert.equal(p.packages.length,1,'Repeated prepare is idempotent');
run(file('v2','v1'));
assert(p.packages[0].stale);
assert.deepEqual(p.packages[0].documentIds,['v1'],'Frozen package retains original document versions');
fails({type:'receipt',reference:'APP-TEST',receivedAt:'2026-11-07',url:'https://example.org/receipt',packageId:first.id},/current package/);
for(const r of p.requirements) run({type:'requirement',id:r.id,state:'reviewed',reviewer:'Reviewer',note:'Reviewed updated plans',documentIds:['v2']});
reviewAreas();run({type:'prepare',reviewer:'Reviewer',reviewed:true});
const receipt={type:'receipt',reference:'APP-TEST',receivedAt:'2026-11-07',url:'https://example.org/receipt',packageId:W.currentPackage(p,'initial').id};
run(receipt);run(receipt);assert.equal(p.receipts.length,1);assert.equal(p.stage,'submitted');
fails({type:'prepare',reviewer:'Reviewer',reviewed:true},/already filed/);
const round={type:'review_round',department:'Building',sourceDate:'2026-11-08',url:'https://example.org/review',originalText:'Show footing detail on sheet S2.',items:['Show footing detail on sheet S2.'],confirmed:true,sourceLocator:'Page 1, comment 1'};
run(round);run(round);assert.equal(p.rounds.length,1);
const cid=p.corrections[0].id;
fails({type:'accept_correction',id:cid,note:'Looks done',url:'https://example.org/review'},/resubmission receipt/);
fails({type:'issuance',permitNumber:'P-TEST',issuedAt:'2026-11-10',url:'https://example.org/permit'},/open correction/);
fails({type:'correction',id:cid,state:'response_prepared',owner:'Engineer',response:'Updated.'},/Attach a revision/);
run(file('v3','v1'));
run({type:'correction',id:cid,state:'response_prepared',owner:'Engineer',response:'Footing detail added to S2.',documentIds:['v3']});
run({type:'prepare',kind:'resubmission',reviewer:'Builder',reviewed:true});
assert.equal(p.corrections[0].state,'response_prepared','Preparing is not submitting');
const resubmit=W.currentPackage(p,'resubmission');
run({type:'receipt',reference:'APP-TEST',receivedAt:'2026-11-09',url:'https://example.org/resubmission',packageId:resubmit.id});
assert.equal(p.corrections[0].state,'resubmitted');
run({type:'accept_correction',id:cid,note:'Reviewer cleared comment 1.',url:'https://example.org/acceptance'});
run({type:'issuance',permitNumber:'P-TEST',issuedAt:'2026-11-10',url:'https://example.org/permit'});
assert.equal(p.stage,'issued');
assert.equal(W.connection.connected,false);assert.equal(W.connection.lastSuccessfulSync,null);
assert.match(W.responseLetter(p),/Footing detail added/);
const before=JSON.stringify(p);W.apply(p,{type:'application',description:'Updated scope'});assert.equal(JSON.stringify(p),before,'Transitions do not mutate earlier records');
let q=W.create(report);q=W.apply(q,{type:'sync_report',report});assert.equal(q.siteVersion,2);
assert.throws(()=>W.apply(q,{type:'sync_report',report:{...report,parcel:{...report.parcel,id:'other'}}}),/different property/);
console.log('Permit lifecycle verified: evidence gates, version invalidation, frozen packages, idempotency, correction/resubmission/acceptance, issuance, disconnected adapter.');
